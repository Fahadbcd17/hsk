const fs=require('fs'),assert=require('assert');
const words=[];
for(let level=1;level<=4;level++){
 let rows=fs.readFileSync(`tools/hsk-2012-${level}.txt`,'utf8').trim().split(/\r?\n/).map(line=>{const [zh,traditional,numeric,py,en]=line.split('\t');assert(zh&&py&&en);return {zh,py,en};});
 // The source expands the paired conjunction 因为……所以…… into two rows.
 // Keep it as one study entry to retain the conventional 150-entry level.
 if(level===2){const i=rows.findIndex(w=>w.zh==='因为');rows[i]={zh:'因为……所以……',py:'yīnwèi…suǒyǐ…',en:'because … therefore … (paired conjunction)'};rows=rows.filter(w=>w.zh!=='所以');}
 assert.equal(rows.length,[0,150,150,300,600][level]);
 words.push(...rows.map((w,i)=>({...w,level,id:`hsk2012-${level}-${i+1}`,part:Math.floor(i/150)+1})));
}
fs.writeFileSync('vocabulary-exams.js','/* HSK 2.0 (2012) lists: https://github.com/glxxyz/hskhsk.com\n * See tools/HSK-2012-LICENSE.txt and VOCABULARY-SOURCES.md.\n * Generated by tools/build-vocabulary.cjs. */\n(()=>{const words='+JSON.stringify(words)+';window.HSK_VOCAB_EXAMS={words(){return words;}};})();\n');
console.log('Built',words.length,'vocabulary entries.');
